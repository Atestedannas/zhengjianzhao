class BeautyLevel:
    """美颜等级.

    【证件照合规约束 — 见 docs/IMAGE_QUALITY_STANDARD.md】
    证件照对外出图只允许 OFF(0) 与 COMPLIANT(1) 两档：
      * COMPLIANT 即「自然微调」，参数被 _clamp_compliant() 硬性锁死在
        公安/政务证件照红线内（磨皮 ≤20%、保留 ≥85% 原生纹理、不改骨相）。
      * LIGHT / MEDIUM / HIGH 降级为**内部对比测试**档位，真实出图时
        同样会被 _clamp_compliant() 压回合规上限，不会产生「塑料脸」。

    ARTISTIC(4) 是**非证件照**的艺术档（写真/社交图）：强度按「PS 中等
    修图」观感给出，不经 _clamp_compliant。调用方（pipeline）在该档必须
    显式传 compliant=False，且只允许在非证件照流程暴露。

    枚举数值保持不变（OFF=0,LIGHT=1,MEDIUM=2,HIGH=3），
    以兼容既有 API 请求体与数据库里存的历史值。
    """
    OFF = 0          # 关闭（原图直出）
    COMPLIANT = 1    # ★ 自然微调：证件照唯一对外推荐档位（= 数值 1，别名 LIGHT）
    LIGHT = 1        # 兼容旧命名，语义等同 COMPLIANT
    MEDIUM = 2       # 内部测试档（会被红线钳制）
    HIGH = 3         # 内部测试档（会被红线钳制）
    ARTISTIC = 4     # 艺术档：仅非证件照流程（调用方须 compliant=False）
    # ★ 影楼精修档：比 COMPLIANT 强得多，但仍然**只做色彩与质感**，不做几何改动。
    # 与 ARTISTIC 的区别：ARTISTIC 是「艺术化」（弱磨皮 + 通透，偏写真风），
    # STUDIO 是「影楼证件照精修」（强磨皮 + 匀肤 + 塑形 + 白净，偏出片风）。
    STUDIO = 5


# ============================================================ 强度参数

@dataclass(frozen=True)
class _Params:
    """单等级的全部强度参数（0~1，除 gamma 外）."""
    smooth: float      # 高频（毛孔/噪点）压制强度
    fine_keep: float   # 高频保留比例下限（防止塑料脸）
    blemish: float     # 中频（斑点/痘印/色块）压制强度
    chroma: float      # 色度匀肤强度
    shine: float       # 去油光强度
    brighten: float    # 提亮强度
    gamma: float       # 提亮曲线（越小越亮）
    clarity: float     # 通透感（中低频对比回填）
    sharpen: float     # 眼部锐化强度
    # ---- 分区域处理系统（本轮新增）----
    tone: float = 0.0      # 分区域低频肤色修正强度（额头/两颊/下颌/脖子各自拉向参考肤色）
    texture: float = 0.0   # 纹理回注强度（把磨皮拿走的毛孔级细节按比例补回）
    feature: float = 0.0   # 五官轮廓带局部增强强度（眼/眉/鼻翼/唇缘）
    # ---- 局部色斑抑制（P1 新增，见 _retouch ⑮）----
    # 【为什么必须独立成轴，不能塞进 chroma】
    #   * chroma 是「中尺度匀肤」：参考半径 0.27·iod（1024 工作图上约 48px），
    #     把一片区域拉向该区域均值，管的是额头偏黄/两颊偏红这类色块；
    #   * 痘印/红斑/晒斑是「小尺度色度异常」：半径约 0.18·iod（≈32px），
    #     特征是「比紧邻的皮肤红一块/黄一块」。用 48px 参考去匀它，
    #     参考值本身已被这块斑污染，压不动。
    # 实测（test_photo.jpg 皮肤区 15 万 px）：L 中频 |mid| p90 仅 0.71 级
    # （8bit 量化直接吞掉，blemish 轴实际空转），而 a*/b* 局部偏离 p90
    # 有 2.3~3.2 级、>3 级像素占约 5%。=> **看得见的瑕疵在色度，不在亮度**。
    # 本轴只压「超出邻域」的那部分 a*/b*，不动像素绝对色度，
    # 所以脸颊健康红润、整体肤色类型、五官几何全部保留。
    spot: float = 0.0      # 局部色斑抑制强度（0~1，合规档 0.85）
    # ---- 磨皮算子尺度（相对瞳距）----
    # 【为什么放进参数表】「磨皮半径」不是常数而是**风格选择**：
    #   证件照要「毛孔仍在」（r≈0.055·iod，覆盖 3~6px 痘印尺度）；
    #   影楼精修要「皮肤像绸缎」（r≈0.10·iod，覆盖 8~14px 的色块与粗糙区），
    #   两者用同一套算子、只是尺度不同。写死成模块常量就只能二选一。
    # 默认值 = 历史常量（0.055 / 90 / 520），保证 COMPLIANT 档数值零漂移。
    fine_r: float = 0.055
    sigma_fine: float = 90.0
    eps_mid: float = 520.0
    # ---- 影楼精修专属强度（COMPLIANT 档全部为 0，等于关闭）----
    sculpt: float = 0.0    # 明暗塑形（高光提亮 + 结构阴影加深，做立体感）
    fill: float = 0.0      # 补光（把面部中低频阴影抬亮，去掉「脏/灰」）
    wb: float = 0.0        # 皮肤白平衡（去黄、补血气，向干净肤色靠）
    eye_polish: float = 0.0  # 眼妆级精修（眼白提净 + 虹膜清晰 + 睫毛加深）
    under_eye: float = 0.0   # 眼袋/泪沟提亮（影楼最见效的一步：去疲惫感）


# ---- 证件照美颜红线（「修饰瑕疵，保留真实」口径，任何档位都不得突破）----
# 【2026-10 二次收紧】用户实测反馈：默认档仍有塑料感/光影被抬平。证件照的
# 第一原则是「越像本人越好」：磨皮只去临时瑕疵，毛孔与光影必须留在原片。
COMPLIANT_MAX_SMOOTH = 0.12     # 磨皮力度硬上限 ≤ 12%
COMPLIANT_MAX_BLEMISH = 0.18    # 仅去临时性痘印/红肿，保留痣与特征
COMPLIANT_MAX_CHROMA = 0.15     # 肤色均匀化上限（0.30 会把血色匀成苍白；再降保留气血感）
COMPLIANT_MAX_BRIGHTEN = 0.08   # 提亮 ≤ 8%（保留面部自然明暗，不做「打光板」）
COMPLIANT_MIN_FINE_KEEP = 0.90  # 原生纹理（毛孔）保留 ≥ 90%（禁止涂抹感）
COMPLIANT_MAX_SHINE = 0.10      # 去油光仅压镜面高光
COMPLIANT_MAX_CLARITY = 0.10    # 通透感回填（立体感的主要来源，保持不变）
COMPLIANT_MAX_SHARPEN = 0.06    # 眼神光级微锐化，禁止改变五官立体光影

# 【两条红线互相约束】磨皮 ≤12% 与纹理保留 ≥90% 不能同时取满：
# 12% 的压制只剩 88% 纹理，已经越过「保留 ≥90%」。因此**实际生效上限是 10%**
# （= 1 - COMPLIANT_MIN_FINE_KEEP），COMPLIANT_MAX_SMOOTH 只是不可越过的硬顶。
# 出图档的 smooth 参数取 0.08（约 8% 磨皮），自适应强度再向下浮动。
COMPLIANT_MAX_FINE_REMOVE = 1.0 - COMPLIANT_MIN_FINE_KEEP   # = 0.10

# ---- 分区域肤色修正预算（低频，通道单位）----
# 【为什么需要这一层】整脸磨皮/匀肤只能压「高频斑点」和「中频色块」，
# 而证件照最常见的脏感来自**低频区域色差**：额头偏黄、两颊偏红、
# 下颌偏暗、脖子与脸不是一个色。低频色差不是瑕疵，是「区域性的肤色偏移」，
# 只能靠「分区域统计 → 拉向整脸参考肤色」来修，磨皮再强也修不掉。
# 预算按通道单位给（L/a/b 均为 0~255 尺度），上限刻意很小：
# 只允许「同一张脸的左右/上下更一致」，不允许把肤色整体改掉（身份特征）。
COMPLIANT_MAX_TONE_SHIFT_L = 7.0    # 区域亮度向整脸中位数靠拢的上限（±7 级）
COMPLIANT_MAX_TONE_SHIFT_A = 5.0    # 区域红度（血色）修正上限（±5 a*）
COMPLIANT_MAX_TONE_SHIFT_B = 5.0    # 区域黄度修正上限（±5 b*）
TONE_GRID = 4                       # 区域网格：4x4（额头/太阳穴/两颊/鼻/口周/下颌/脖子）

# ---- 纹理回注预算 ----
# 「保留纹理」不能只靠「少磨皮」：磨皮算子再保边，也会把毛孔级起伏压掉一部分。
# 这里把磨皮**实际拿走**的那部分细节按比例回注到平坦皮肤上（强边不回注，
# 避免把睫毛/鼻翼拉出白边），让「磨皮可感知、毛孔仍在」同时成立。
#
# 【2026-11 P0：0.62 → 0.40】链路里有两级锐化 + 本回注同时把高频往回补，
# 实测合规档净高频比 1.01~1.04（越修越锐），磨皮完全不可见。去掉一级锐化
# 并给皮肤区降权后，回注也必须收：0.40 仍远高于「纹理保留 ≥90%」红线所需的
# 量（磨皮只压 8~10%，回注 40%×8%=3.2%，净纹理保留 ≈95%），但能把净高频
# 比压到 0.92~0.96 的目标区间。精修档有独立的 _STUDIO_BUDGET，不受影响。
TEXTURE_REINJECT_MAX = 0.40         # 合规档最多回注磨皮拿走的 40%

# ---- P1 局部色斑抑制预算 ----
# spot 压的是「超出邻域」的 a*/b* 偏离（不是绝对色度），单像素改变量天然
# 被 clip(±8) 与软阈值限住；这个系数是可调旋钮，不动任何合规红线常量。
# 【2026-11 P2 多样本重标定】P1 的 (0.45, 1.00) 只在 1 张高清样张上标定。
# 补测第 2 张真人样张（231×268 蓝底证件照，走 295×413 直接出图路径）后发现：
# 色斑降仅 2.5%（高清 4.4%）、皮肤区色差降 23.9%（高清 35.8%）。
# 9 组扫描在两张真人样张上逐项验证，(0.60, 1.30) 是双赢点：
#   高清 : 肤色区色差 35.8%→38.3%  色斑 4.4%→5.6%
#   小图 : 肤色区色差 23.9%→28.3%  色斑 2.5%→3.2%
# 身份相似度 0.99956→0.99953 / 0.99960→0.99960，ITA 肤色档不变，
# 出图尺寸、warnings、mean_abs / p95 均无变化；脸部放大目视无假白、
# 无色块、五官不糊。SPOT_MAX_DELTA=4.0 仍对单像素 a*/b* 硬钳制 ——
# gain 变大只是让更多像素吃满钳制，绝不会绕过合规上限。
SPOT_GAIN = 1.30
# 邻域参考半径（相对瞳距）。最终出图是 295×413 且经 JPEG 4:2:0 色度抽样：
# 0.18·iod（≈32px 工作图 → 9px 出图）的痘印级改动会被缩图抹掉，实测
# 色斑只降 0.6%；中等色块才在缩图后仍可见。P1 取 0.45·iod，P2 在两张
# 真人样张上复扫后取 0.60·iod（≈106px 工作图 → 30px 出图）。
SPOT_RADIUS_RATIO = 0.60
# 软阈值：偏离 ≤lo 属自然肤色起伏全额保留，≥hi 才压满。
SPOT_GATE_LO = 0.8
SPOT_GATE_HI = 6.0
# 【红线钳制】spot 是新增轴，绝不能绕过 _clamp_compliant：这里把单像素
# a*/b* 改变量硬夹在 ±4 级 —— 与分区肤色 ±5 / 唇色 ±4 同量级，且远低于
# 「改变肤色类型」的幅度。无论上游把 spot / gain / 档位改成多少，都不会越界。
SPOT_MAX_DELTA = 4.0
# 中尺度匀肤（chroma）的色偏门控。扫描确认放宽到 (0.5,4.0) 无额外收益，
# 保持 P0 标定值；保留旋钮便于后续 A/B 归因。
CHROMA_GATE_LO = 0.8
CHROMA_GATE_HI = 6.0

# ---- P1 气色预算旋钮（全部在已有合规上限内，只是把没吃满的份额用足）----
# 唇色 need 门控：实测唇区 (a−a_ref) p50=16、p90=25，旧门控 (10,30) 让
# need 均值只有 0.666 → 8 个 a* 的合规预算实际只吃到 5.3。放宽到 (14,36)
# 可吃到 6.5，气色更足且仍不越 COMPLIANT_MAX_LIP_A=8 红线。
LIP_NEED_LO = 14.0
LIP_NEED_HI = 36.0
# 眼神光：旧实现只取眼区亮度 p97 以上，实测眼区平均 ΔL 仅 0.03（等于没做）。
# 分位放宽到 92 让「有神」真正可见；提亮幅度仍由 catchlight 预算钳住。
EYE_CATCHLIGHT_PCT = 92.0
# 分区肤色网格：默认 4×4 太粗，中等尺度色块落在同一格里被平均掉。
# P1 生产口径标定为 6×6：两张样张的区域色差下降 17.9%→21.1% / 10.4%→20.9%，
# 目视无格线感（网格上采样后仍有 _fast_blur 柔化）。
